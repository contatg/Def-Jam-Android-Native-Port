"""One set of agent instructions for every tool, and the per-tool copies derived from it.

`AGENTS.md` is the instruction file (Codex reads it as is). `CLAUDE.md` imports it with `@AGENTS.md` and adds
only notes for Claude Code. Codex's default limit for the combined project instructions it discovers is 32 KiB (`project_doc_max_bytes`, which
can be changed), so `AGENTS.md` stays under 30 as a convention; this checks the one file, not the whole chain.
Skills and sub-agent briefs are written once under docs/agent/ and copied for each tool by
scripts/sync-agent-adapters.py; a copy that differs from its source fails here. Line endings are ignored,
since a checkout may convert them.
"""
import importlib.util
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIMIT = 30 * 1024


def read(name):
    with open(os.path.join(ROOT, name), 'rb') as f:
        return f.read().replace(b'\r\n', b'\n').decode('utf-8')


def sync_module():
    spec = importlib.util.spec_from_file_location('sync_agent_adapters',
                                                  os.path.join(ROOT, 'scripts', 'sync-agent-adapters.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_claude_md_imports_agents_md():
    lines = [l for l in read('CLAUDE.md').splitlines() if l.strip()]
    assert lines[0] == '@AGENTS.md', 'CLAUDE.md must start with the import so Claude Code loads AGENTS.md'
    assert len(read('CLAUDE.md').encode()) < 6 * 1024, 'CLAUDE.md is for Claude-only notes; shared rules go in AGENTS.md'


def test_agents_md_fits_codex_budget():
    size = len(read('AGENTS.md').encode())
    assert size < LIMIT, 'AGENTS.md is %d bytes; keep AGENTS.md under the 32 KiB default Codex limit with room to spare. Move detail to docs/agent/' % size


def test_agents_md_has_nothing_only_one_tool_understands():
    text = read('AGENTS.md')
    for phrase in ('Sonnet', 'Haiku', 'subagent_type', 'Bash tool', 'run_in_background'):
        assert phrase not in text, '%r belongs in CLAUDE.md, not in the shared instructions' % phrase


def test_every_playbook_agents_md_points_to_exists():
    paths = set(re.findall(r'docs/agent/[\w./-]*\w', read('AGENTS.md')))
    assert paths, 'AGENTS.md should point to docs/agent/'
    missing = [p for p in sorted(paths) if not os.path.exists(os.path.join(ROOT, p))]
    assert not missing, 'AGENTS.md names files that do not exist: %s' % missing


def test_every_script_agents_md_names_exists():
    names = set(re.findall(r'\bscripts/([\w-]+\.(?:py|ps1))\b', read('AGENTS.md')))
    missing = [n for n in sorted(names) if not os.path.exists(os.path.join(ROOT, 'scripts', n))]
    assert not missing, 'AGENTS.md names scripts that do not exist: %s' % missing


def test_skill_and_brief_copies_match_their_sources():
    problems = sync_module().drift()
    assert not problems, 'run python scripts/sync-agent-adapters.py: %s' % problems


def test_sources_have_only_name_and_description():
    sync = sync_module()
    generated = sync.generate()
    assert any(p.startswith('.codex/skills/') for p in generated) and any(p.startswith('.claude/skills/') for p in generated)
    assert any(p.startswith('.claude/agents/') for p in generated)


def _sandbox(sync, tmp_path, monkeypatch):
    """The sync script pointed at a throw-away tree with one skill and one brief."""
    skill = tmp_path / 'docs/agent/skills/demo'
    skill.mkdir(parents=True)
    (skill / 'SKILL.md').write_text('---\nname: demo\ndescription: Does a demo.\n---\n\nBody.\n')
    briefs = tmp_path / 'docs/agent/briefs'
    briefs.mkdir(parents=True)
    (briefs / 'log-triage.md').write_text('---\nname: log-triage\ndescription: Reads logs.\n---\n\nBrief.\n')
    monkeypatch.setattr(sync, 'REPO', str(tmp_path))
    monkeypatch.setattr(sync, 'SKILLS_SRC', str(tmp_path / 'docs/agent/skills'))
    monkeypatch.setattr(sync, 'BRIEFS_SRC', str(briefs))


def test_sync_writes_detects_drift_and_removes_stale_copies(tmp_path, monkeypatch, capsys):
    sync = sync_module()
    _sandbox(sync, tmp_path, monkeypatch)
    assert sync.main(['--check']) == 1                                  # nothing written yet
    assert sync.main([]) == 0
    assert sync.main(['--check']) == 0
    for base in ('.claude/skills', '.codex/skills'):
        assert (tmp_path / base / 'demo/SKILL.md').read_text().startswith('---\nname: demo\n')
    agent = (tmp_path / '.claude/agents/log-triage.md').read_text()
    assert 'model: haiku' in agent and 'Generated by scripts/sync-agent-adapters.py' in agent

    (tmp_path / '.codex/skills/demo/SKILL.md').write_text('hand edited\n')
    assert any(p.startswith('differs: .codex/skills/demo') for p in sync.drift())
    sync.main([])
    assert sync.main(['--check']) == 0

    (tmp_path / 'docs/agent/skills/demo/SKILL.md').unlink()
    (tmp_path / 'docs/agent/skills/demo').rmdir()
    assert any(p.startswith('stale: ') for p in sync.drift())
    sync.main([])
    assert not (tmp_path / '.claude/skills/demo/SKILL.md').exists()


def test_sync_never_removes_a_file_it_did_not_generate(tmp_path, monkeypatch):
    sync = sync_module()
    _sandbox(sync, tmp_path, monkeypatch)
    mine = tmp_path / '.claude/skills/personal/SKILL.md'
    mine.parent.mkdir(parents=True)
    mine.write_text('---\nname: personal\ndescription: Not generated.\n---\n')
    sync.main([])
    assert mine.exists() and sync.drift() == []


def test_sync_rejects_extra_frontmatter_and_a_wrong_name(tmp_path, monkeypatch):
    import pytest
    sync = sync_module()
    _sandbox(sync, tmp_path, monkeypatch)
    skill = tmp_path / 'docs/agent/skills/demo/SKILL.md'
    skill.write_text('---\nname: demo\ndescription: x\nmodel: opus\n---\n')
    with pytest.raises(SystemExit):
        sync.generate()
    skill.write_text('---\nname: other\ndescription: x\n---\n')
    with pytest.raises(SystemExit):
        sync.generate()
