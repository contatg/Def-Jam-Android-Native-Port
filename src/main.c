/*
 * Vectored Exception Handler for crash diagnostics.
 *
 * When the recompiled game hits an access violation, this handler prints
 * the faulting address, all Xbox register values, and a native stack trace.
 * This is your primary debugging tool during bring-up.
 *
 * Customize this for your game:
 *   - Add game-specific address checks (GPU register probes, etc.)
 *   - Add dumps of game-specific globals (heap handles, state flags)
 *   - Add SEH simulation if your game uses __try/__except
 */
/* Name the guest function a fault happened in, and recover the call chain.
 *
 * Recompiled code faults as ordinary native code, so the exception record
 * carries a host RIP and nothing else -- there is no guest program counter to
 * report, and the host address changes every build. Two things recover the
 * guest view:
 *
 *   - every generated function is a real symbol in the image (sub_005A03C0
 *     and so on), so the linker's PDB already maps host address back to guest
 *     function. dbghelp turns an anonymous RIP into that name.
 *
 *   - every lifted call pushes its guest return address onto the guest stack
 *     before jumping, so the stack still holds the chain. Scanning up from esp
 *     for values inside the code sections recovers it.
 *
 * ponytail: the stack scan is a scan, not a frame walk -- these are FPO frames
 * with no reliable ebp chain, so there is nothing to walk. It over-reports,
 * since addresses from returned-from calls linger below esp, but naming the
 * guest function is the whole question at a fault.
 *
 * Requires linking dbghelp and keeping the .pdb beside the .exe.
 */
static void print_guest_context(void *rip)
{
#if defined(_WIN32)
    /* SYMBOL_INFO is variable-length: the name is written past the struct, so
     * it must be over-allocated with MaxNameLen set to the slack. */
    char buf[sizeof(SYMBOL_INFO) + 256];
    SYMBOL_INFO *sym = (SYMBOL_INFO *)buf;
    DWORD64 disp = 0;

    memset(buf, 0, sizeof(buf));
    sym->SizeOfStruct = sizeof(SYMBOL_INFO);
    sym->MaxNameLen = 255;
    if (SymFromAddr(GetCurrentProcess(), (DWORD64)(uintptr_t)rip, &disp, sym))
        fprintf(stderr, "  in %s+0x%llX\n",
                sym->Name, (unsigned long long)disp);
#else
    /* The generated functions are ordinary symbols here too; the dynamic
     * loader's table names them as long as the link exports them. */
    Dl_info info;

    if (dladdr(rip, &info) && info.dli_sname)
        fprintf(stderr, "  in %s+0x%llX\n", info.dli_sname,
                (unsigned long long)((uintptr_t)rip - (uintptr_t)info.dli_saddr));
#endif

    /* What the pointer registers were actually pointing at.
     *
     * A fault through a structure field is the common shape here, and the
     * registers alone never say which field: they give the object, not its
     * contents. Dumping a little of each pointed-to object turns "esi was
     * 0xFFFFFFFF" into "this field of that object was never written", which
     * is the question. Each read is bounds-checked because at least one of
     * these registers is wild by definition at a fault. */
    if (g_xbox_mem_offset) {
        static const char *const names[] = { "eax", "ecx", "edx", "ebx", "esi", "edi" };
        const uint32_t regs[] = { g_eax, g_ecx, g_edx, g_ebx, g_esi, g_edi };
        size_t r;

        fprintf(stderr, "  guest memory at the pointer registers:\n");
        for (r = 0; r < sizeof(regs) / sizeof(regs[0]); r++) {
            uint32_t va = regs[r];
            int w;
            if (va < XBOX_BASE_ADDRESS || (uint64_t)va + 32 > XBOX_TOTAL_RAM) {
                fprintf(stderr, "    %s 0x%08X  (not a guest pointer)\n",
                        names[r], va);
                continue;
            }
            fprintf(stderr, "    %s 0x%08X ->", names[r], va);
            for (w = 0; w < 8; w++)
                fprintf(stderr, " %08X",
                        *(const uint32_t *)((uintptr_t)g_xbox_mem_offset + va + w * 4));
            fprintf(stderr, "\n");
        }
    }

    if (g_xbox_mem_offset && g_esp) {
        const uint32_t *sp =
            (const uint32_t *)((uintptr_t)g_xbox_mem_offset + g_esp);
        int shown = 0, i;
        fprintf(stderr, "  guest stack (scan, not a walk -- includes stale frames):\n");
        for (i = 0; i < 256 && shown < 24; i++) {
            uint32_t v = sp[i];
            if (v > g_xbox_code_lo && v < g_xbox_code_hi) {
                fprintf(stderr, "    [esp+%-4d] 0x%08X\n", i * 4, v);
                shown++;
            }
        }
    }
}


/* ---- Does the lifted CRT still divide correctly? ----------------------
 *
 * The recompiler used to drop `rcr`, which is the instruction MSVC's 64-bit
 * divide helpers use to shift a 64-bit pair one bit right. Without it the
 * shift happened on one half and the bit that should have crossed vanished,
 * so _alldiv, _aulldiv, _allrem and _aullrem were all silently wrong whenever
 * the divisor did not fit in 32 bits. Silently is the problem: nothing faults,
 * a number is simply not the number.
 *
 * So the four of them are exercised against answers computed here, on the way
 * up, with operands that force the path that uses `rcr`. Off unless
 * RECOMP_SELFTEST is set, because it costs a few microseconds and the answer
 * only changes when the lifter does -- but run it after any lifter change.
 *
 * The guest calling convention is the one the generated code uses: push the
 * arguments right to left, push a return address, call, and read the result
 * out of the guest edx:eax. The callees are __stdcall, so they clean up.
 */
typedef void (*recomp_func_t)(void);
/* Guest memory, the same translation the generated code uses. Spelled out
 * here rather than including recomp_types.h, which would drag the whole
 * register model into a file that only needs four stack pushes. */
#define GUEST32(va) (*(volatile uint32_t *)((uintptr_t)(va) + (uintptr_t)g_xbox_mem_offset))
extern recomp_func_t recomp_lookup(uint32_t xbox_va);
int recomp_dispatch_init(void);   /* generated, recomp_dispatch.c */

static void recomp_selftest(void)
{
    /* The four helpers that contain `rcr`, by address. Which of them is the
     * quotient and which the remainder is not asserted here: the first attempt
     * guessed, got one wrong, and reported a correct function as broken. The
     * test instead accepts either answer and says which it saw, so it is
     * checking arithmetic rather than a naming hunch. */
    static const uint32_t helpers[] = {
        0x00201470u, 0x00202930u, 0x002032C0u, 0x00209630u,
    };
    /* A divisor above 2^32 is what takes the rcr path. Both operands are
     * positive, so the signed and unsigned helpers agree. */
    const uint64_t dividend = 0x0000123456789ABCull;
    const uint64_t divisor  = 0x0000000100000007ull;
    const uint64_t quotient = dividend / divisor;
    const uint64_t remainder = dividend % divisor;
    size_t i;
    int bad = 0;

    if (!getenv("RECOMP_SELFTEST"))
        return;

    for (i = 0; i < sizeof(helpers) / sizeof(helpers[0]); i++) {
        recomp_func_t fn = recomp_lookup(helpers[i]);
        uint32_t saved_esp = g_esp;
        uint64_t got;

        if (!fn) {
            fprintf(stderr, "  [SELFTEST] 0x%08X is not in the dispatch table\n",
                    helpers[i]);
            bad++;
            continue;
        }

        g_esp -= 4; GUEST32(g_esp) = (uint32_t)(divisor >> 32);
        g_esp -= 4; GUEST32(g_esp) = (uint32_t)divisor;
        g_esp -= 4; GUEST32(g_esp) = (uint32_t)(dividend >> 32);
        g_esp -= 4; GUEST32(g_esp) = (uint32_t)dividend;
        g_esp -= 4; GUEST32(g_esp) = 0;        /* return address, unused */
        fn();
        got = ((uint64_t)g_edx << 32) | g_eax;
        g_esp = saved_esp;

        if (got == quotient || got == remainder) {
            fprintf(stderr, "  [SELFTEST] 0x%08X -> %s, correct\n", helpers[i],
                    got == quotient ? "quotient" : "remainder");
        } else {
            fprintf(stderr, "  [SELFTEST] 0x%08X(0x%llX, 0x%llX) = 0x%llX, "
                            "neither the quotient 0x%llX nor the remainder "
                            "0x%llX\n", helpers[i],
                    (unsigned long long)dividend, (unsigned long long)divisor,
                    (unsigned long long)got, (unsigned long long)quotient,
                    (unsigned long long)remainder);
            bad++;
        }
    }
    fprintf(stderr, "  SELFTEST: 64-bit divide helpers %s\n",
            bad ? "FAILED" : "all correct");

    /* The CRT's x87 fmod intrinsic, _CIfmod (0x0020144E): arguments on the
     * register stack, x in st(1) and y in st(0); the result replaces them, one
     * slot shallower. APT reduces angles with it when it decomposes a clip's
     * matrix (sub_00164920), and wrong scale and rotation came out of that. */
    {
        recomp_func_t fn = recomp_lookup(0x0020144Eu);
        uint32_t saved_esp = g_esp;
        int top0 = g_fp_top;
        /* The values APT feeds it: atan2 of an identity matrix is 0 (or -0),
        * reduced modulo pi. Zero takes the CRT's special-value path. */
        static const double xs[] = { 7.5, 0.0, -0.0, 1.5707963705062866 };
        const double y = 3.1415927410125732;
        uint32_t flag_saved = GUEST32(0x002FAD20u);   /* the CRT picks its path on this */
        int pass, k;
        for (pass = 0; pass < 2 && fn; pass++)
        for (k = 0; k < 4; k++) {
            const double x = xs[k];
            GUEST32(0x002FAD20u) = (uint32_t)pass;
            top0 = g_fp_top;
            g_fp_top = (g_fp_top + 7) & 7; g_fp_stack[g_fp_top] = x;
            g_fp_top = (g_fp_top + 7) & 7; g_fp_stack[g_fp_top] = y;
            g_esp -= 4; GUEST32(g_esp) = 0;    /* return address, unused */
            fn();
            fprintf(stderr, "  [SELFTEST] _CIfmod(%g, %g) [flag %d] = %g (expected %g); net x87 depth %d (expected 1)\n",
                    x, y, pass, g_fp_stack[g_fp_top], fmod(x, y), (top0 - g_fp_top) & 7);
            g_esp = saved_esp;
            g_fp_top = top0;
        }
        GUEST32(0x002FAD20u) = flag_saved;
    }
    fflush(stderr);
}

