#!/usr/bin/env python3
"""Write the per-tool copies of the agent skills and briefs from their single source.

    python scripts/sync-agent-adapters.py            write what is missing or different
    python scripts/sync-agent-adapters.py --check    change nothing; exit 1 if any copy differs (CI and unit tests)

Sources, edited by hand:
    docs/agent/skills/<name>/SKILL.md    a skill; frontmatter is `name` and `description` only
    docs/agent/briefs/<name>.md          a sub-agent brief; frontmatter is `name` and `description`

Copies, generated (the first line after the frontmatter says so; do not edit them):
    .claude/skills/<name>/SKILL.md       Claude Code
    .codex/skills/<name>/SKILL.md        Codex
    .claude/agents/<name>.md             Claude Code sub-agents (the brief plus the tool and model it runs with)

Codex custom agents (documented as .codex/agents/*.toml) are not generated yet: the schema was not available
when this was written. The brief is plain text that any agent can be given in a delegation prompt
(docs/agent/delegation.md). Skills are copied to .codex/skills, which Codex CLI discovers (reported working
on 0.162); its documentation recommends .agents/skills, so change SKILL_TARGETS if you prefer that path.
Standard library only.
"""
import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS_SRC = os.path.join(REPO, 'docs', 'agent', 'skills')
BRIEFS_SRC = os.path.join(REPO, 'docs', 'agent', 'briefs')
SKILL_TARGETS = ('.claude/skills', '.codex/skills')
AGENT_TARGET = '.claude/agents'
MARK = '<!-- Generated by scripts/sync-agent-adapters.py from %s. Edit that file, not this one. -->'
# What each brief runs with in Claude Code. A brief does not see the repo's instructions
# (omitClaudeMd), so the brief itself carries what it needs.
CLAUDE_AGENT = {
    're-reader': {'tools': 'Read, Grep, Glob, Bash', 'model': 'sonnet', 'omitClaudeMd': 'true'},
    'log-triage': {'tools': 'Read, Grep, Glob, Bash', 'model': 'haiku', 'omitClaudeMd': 'true'},
}
FRONT_RE = re.compile(r'\A---\n(.*?)\n---\n(.*)\Z', re.S)


def read(path):
    with open(path, encoding='utf-8', newline='') as f:
        return f.read().replace('\r\n', '\n')


def split(text, where):
    m = FRONT_RE.match(text)
    if not m:
        raise SystemExit('%s: missing the --- frontmatter ---' % where)
    keys = dict(re.findall(r'^([A-Za-z][\w-]*):\s*(.*)$', m.group(1), re.M))
    return m.group(1), keys, m.group(2)


def check_source(keys, where, expect_name):
    if set(keys) != {'name', 'description'}:
        raise SystemExit('%s: frontmatter must be exactly name and description (got %s)' % (where, sorted(keys)))
    if keys['name'] != expect_name:
        raise SystemExit('%s: name %r must match %r' % (where, keys['name'], expect_name))
    if not keys['description'].strip() or len(keys['description']) > 1000:
        raise SystemExit('%s: description must be 1..1000 characters' % where)


def generate():
    """{relative target path: text}"""
    out = {}
    if os.path.isdir(SKILLS_SRC):
        for name in sorted(os.listdir(SKILLS_SRC)):
            src = os.path.join(SKILLS_SRC, name, 'SKILL.md')
            if not os.path.isfile(src):
                continue
            rel = 'docs/agent/skills/%s/SKILL.md' % name
            front, keys, body = split(read(src), rel)
            check_source(keys, rel, name)
            text = '---\n%s\n---\n%s\n%s' % (front, MARK % rel, body)
            for base in SKILL_TARGETS:
                out['%s/%s/SKILL.md' % (base, name)] = text
    if os.path.isdir(BRIEFS_SRC):
        for fn in sorted(os.listdir(BRIEFS_SRC)):
            if not fn.endswith('.md'):
                continue
            name = fn[:-3]
            rel = 'docs/agent/briefs/%s' % fn
            front, keys, body = split(read(os.path.join(BRIEFS_SRC, fn)), rel)
            check_source(keys, rel, name)
            if name not in CLAUDE_AGENT:
                raise SystemExit('%s: add its tools and model to CLAUDE_AGENT in %s' % (rel, os.path.basename(__file__)))
            extra = ''.join('\n%s: %s' % kv for kv in CLAUDE_AGENT[name].items())
            out['%s/%s.md' % (AGENT_TARGET, name)] = '---\n%s%s\n---\n%s\n%s' % (front, extra, MARK % rel, body)
    return out


def stale():
    """Generated files whose source is gone (only files that carry the marker are ever touched)."""
    wanted = set(generate())
    found = []
    for base in SKILL_TARGETS + (AGENT_TARGET,):
        root = os.path.join(REPO, base)
        for dirpath, _, files in os.walk(root):
            for fn in files:
                rel = os.path.relpath(os.path.join(dirpath, fn), REPO).replace(os.sep, '/')
                if rel not in wanted and 'Generated by scripts/sync-agent-adapters.py' in read(os.path.join(REPO, rel)):
                    found.append(rel)
    return sorted(found)


def drift():
    """Problems, as strings: missing, different, or left over."""
    problems = []
    for rel, text in generate().items():
        path = os.path.join(REPO, rel)
        if not os.path.isfile(path):
            problems.append('missing: ' + rel)
        elif read(path) != text:
            problems.append('differs: ' + rel)
    problems += ['stale: ' + rel for rel in stale()]
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='change nothing; exit 1 if a copy is missing, different or stale')
    args = ap.parse_args(argv)
    problems = drift()
    if args.check:
        for p in problems:
            print(p)
        print('%d adapter problem(s)%s' % (len(problems), '' if not problems else '; run python scripts/sync-agent-adapters.py'))
        return 1 if problems else 0
    wrote = 0
    for rel, text in generate().items():
        path = os.path.join(REPO, rel)
        if not os.path.isfile(path) or read(path) != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            wrote += 1
    for rel in stale():
        os.remove(os.path.join(REPO, rel))
        wrote += 1
    print('%d file(s) written or removed' % wrote)
    return 0


if __name__ == '__main__':
    sys.exit(main())
